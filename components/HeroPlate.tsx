'use client'

import dynamic from 'next/dynamic'
import { useEffect, useRef, useState } from 'react'
import { usePrefersReducedMotion } from '@/lib/client/hooks'

/* The landing page's hero: the studio's own 3D viewer, with the studio's own
   geometry, that a visitor can take hold of and turn.

   It used to be a stock picture of a burger — food the product does not make,
   rendered by software that is not ours. What loads now is the same
   buildPlatingModel() output the chef refines in the studio, so the first thing
   anyone sees is the actual product rather than a promise about it.

   Three loads happen in order, and the page is useful after each one:

     1. the still  (public/hero/<slug>.png, ~250KB, in the HTML)
     2. the model  (public/hero/<slug>.gltf, fetched once the page is idle)
     3. the viewer (three.js, code-split, mounted only when a model is in hand)

   If any of that is unavailable — no WebGL, data saver on, JavaScript off — the
   still stays and the hero is simply a picture, which is what it was before. */

const ModelViewer = dynamic(() => import('./ModelViewer'), { ssr: false })

export const CONCEPTS = [
  { slug: 'classic-centred', name: 'Classic centred', note: 'Round white · sauce pooled · medium build' },
  { slug: 'garden-scatter', name: 'Garden scatter', note: 'Round white · sauce dotted · low build' },
  { slug: 'slate-linear', name: 'Slate linear', note: 'Black slate · sauce dotted · low build' },
] as const

function canRender3d() {
  try {
    // Data saver is not in the DOM lib yet, hence the cast.
    const link = (navigator as Navigator & { connection?: { saveData?: boolean } }).connection
    if (link?.saveData) return false
    const probe = document.createElement('canvas')
    return Boolean(probe.getContext('webgl2') ?? probe.getContext('webgl'))
  } catch {
    return false
  }
}

export default function HeroPlate({
  index,
  onIndexChange,
}: {
  index: number
  onIndexChange: (index: number) => void
}) {
  const concept = CONCEPTS[index]
  // Keyed by slug: switching back to one already seen is instant, and the
  // viewer keeps whatever angle the visitor turned the last plate to.
  const cache = useRef(new Map<string, object>())
  const [gltf, setGltf] = useState<object | null>(null)
  const [live, setLive] = useState(false)
  const [wantsTurntable] = useState(true)
  const reducedMotion = usePrefersReducedMotion()
  // Reduced motion: the plate still turns by hand, it just does not spin on its own.
  const turntable = wantsTurntable && !reducedMotion

  useEffect(() => {
    if (!canRender3d()) return
    // Wait for the browser to be idle: the hero still is already on screen, and
    // nothing here should compete with the rest of the page loading.
    const idle = window.requestIdleCallback ?? ((fn: () => void) => setTimeout(fn, 600))
    const handle = idle(() => setLive(true))
    return () => window.cancelIdleCallback?.(handle as number)
  }, [])

  useEffect(() => {
    if (!live) return
    let cancelled = false
    const cached = cache.current.get(concept.slug)
    if (cached) {
      setGltf(cached)
      return
    }
    // Deliberately NOT clearing the current model: dropping it would unmount the
    // viewer mid-switch and flash the still back for a frame.
    ;(async () => {
      try {
        const res = await fetch(`/hero/${concept.slug}.gltf`)
        if (!res.ok) throw new Error('unavailable')
        const json = await res.json()
        if (cancelled) return
        cache.current.set(concept.slug, json)
        setGltf(json)
      } catch {
        // The still is already showing; there is nothing to fall back to.
      }
    })()
    return () => {
      cancelled = true
    }
  }, [live, concept.slug])

  const showingModel = Boolean(gltf)

  return (
    <div className="hero-plate">
      <div className="rings" />

      <div className="hero-stage">
        {/* The still sits under the canvas rather than beside it, so the moment
            the first frame paints it is simply covered. No crossfade to time. */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src={`/hero/${concept.slug}.png`}
          alt={`${concept.name} — a plating concept generated by FUDDO AI`}
          className="hero-still"
          data-under={showingModel}
          width={1200}
          height={1200}
        />
        {showingModel ? (
          <div className="hero-canvas">
            <ModelViewer gltf={gltf} turntable={turntable} transparent />
          </div>
        ) : null}

        <span className="hero-badge" data-live={showingModel}>
          <i aria-hidden="true" />
          {showingModel ? 'Live 3D' : 'FUDDO render'}
        </span>
      </div>

      <div className="floating f1">
        <span>
          <small>CONCEPT {String(index + 1).padStart(2, '0')}</small>
          <b>{concept.name}</b>
        </span>
      </div>
      <div className="floating f2">
        <i aria-hidden="true">✦</i>
        <span>
          <small>AI GENERATED</small>
          <b>Ready to refine</b>
        </span>
      </div>

      <div className="hero-switch" role="tablist" aria-label="Plating concepts">
        {CONCEPTS.map((c, i) => (
          <button
            key={c.slug}
            role="tab"
            aria-selected={i === index}
            aria-label={c.name}
            title={`${c.name} — ${c.note}`}
            onClick={() => onIndexChange(i)}
          />
        ))}
        <span>{showingModel ? 'Drag the plate to turn it' : concept.note}</span>
      </div>
    </div>
  )
}
